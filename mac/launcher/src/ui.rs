    // -------------------------------------------------------------------------
    // Start a new discovery / playback worker
    // -------------------------------------------------------------------------

    fn start_worker(&self) {
        if self.ivars().worker_running.get() {
            return;
        }

        self.ivars()
            .worker_running
            .set(true);

        self.render_state(
            &AppState::Discovering {
                seconds_remaining: None,
            }
        );


        let (tx, rx) =
            mpsc::channel::<AppState>();

        *self.ivars()
            .receiver
            .borrow_mut() = Some(rx);


        let player_handle =
            Arc::clone(
                &self.ivars().player
            );


        let cancellation =
            Arc::new(
                AtomicBool::new(false)
            );


        *self.ivars()
            .cancellation
            .borrow_mut() =
            Some(
                Arc::clone(&cancellation)
            );


        thread::spawn(move || {
            worker::run_stream_flow(
                tx,
                player_handle,
                cancellation,
            );
        });
    }


    // -------------------------------------------------------------------------
    // Cancel discovery, connection, recovery, or playback by user request.
    // -------------------------------------------------------------------------

    fn cancel_active_session(&self) {
        if let Some(cancellation) = self
            .ivars()
            .cancellation
            .borrow()
            .as_ref()
        {
            cancellation.store(
                true,
                Ordering::Relaxed,
            );
        }


        self.terminate_player();


        // Dropping the receiver invalidates every pending state from the
        // cancelled worker before a later search starts a fresh session.
        self.ivars()
            .receiver
            .borrow_mut()
            .take();


        self.ivars()
            .worker_running
            .set(false);


        // The cancelled worker can no longer report states, so the UI's
        // return to Idle is logged here. The log must end where the UI does.
        logging::state(&AppState::Idle);

        self.render_state(&AppState::Idle);
    }


    // -------------------------------------------------------------------------
    // Show this session's log directory in Finder
    //
    // `source` is how the user asked: it is only reported in Verbose.
    // -------------------------------------------------------------------------

    fn open_logs_folder(
        &self,
        source: &str,
    ) {
        logging::action("Open Logs Folder");

        logging::verbose(
            "UI",
            format_args!(
                "Open Logs Folder invoked via {source}"
            ),
        );

        let Some(directory) = logging::log_directory() else {
            logging::warn(
                "APP",
                format_args!(
                    "No logs folder to open: this session has no log file."
                ),
            );

            return;
        };


        #[cfg(debug_assertions)]
        if UI_SELF_TEST.with(Cell::get) {
            logging::debug(
                "APP",
                format_args!(
                    "Self-test: not opening Finder."
                ),
            );

            return;
        }


        let url =
            NSURL::fileURLWithPath(
                &NSString::from_str(
                    &directory.to_string_lossy()
                )
            );


        // Asks Finder to show the folder and returns immediately.
        let opened =
            NSWorkspace::sharedWorkspace()
                .openURL(&url);


        if opened {
            logging::debug(
                "APP",
                format_args!(
                    "Opened {}",
                    directory.display()
                ),
            );
        } else {
            logging::warn(
                "APP",
                format_args!(
                    "Could not open logs folder {}",
                    directory.display()
                ),
            );
        }
    }


