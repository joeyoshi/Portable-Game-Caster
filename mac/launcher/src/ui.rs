struct AppDelegateIvars {
    window: OnceCell<Retained<NSWindow>>,
    host_label: OnceCell<Retained<NSTextField>>,
    status_label: OnceCell<Retained<NSTextField>>,
    detail_label: OnceCell<Retained<NSTextField>>,
    spinner: OnceCell<Retained<NSProgressIndicator>>,

    retry_button: OnceCell<Retained<NSButton>>,
    search_button: OnceCell<Retained<NSButton>>,
    quit_button: OnceCell<Retained<NSButton>>,
    logs_button: OnceCell<Retained<NSButton>>,

    receiver: RefCell<Option<Receiver<AppState>>>,
    worker_running: Cell<bool>,
    cancellation: RefCell<Option<worker::CancellationToken>>,
    primary_action: Cell<PrimaryAction>,

    // Set by the first shutdown request so that one shutdown produces one
    // action, one narrative, and one exit line.
    quitting: Cell<bool>,

    // Shared ownership of the active ffplay child process.
    //
    // The worker thread launches and monitors it.
    // The AppKit thread can terminate it when the user quits PGC.
    player: Arc<Mutex<Option<Child>>>,
}


#[derive(Clone, Copy)]
enum PrimaryAction {
    Retry,
    Cancel,
    Stop,
}


// -----------------------------------------------------------------------------
// AppDelegate
// -----------------------------------------------------------------------------

define_class!(
    #[unsafe(super(NSObject))]
    #[thread_kind = MainThreadOnly]
    #[ivars = AppDelegateIvars]
    struct AppDelegate;

    unsafe impl NSObjectProtocol for AppDelegate {}

    unsafe impl NSApplicationDelegate for AppDelegate {
        #[unsafe(method(applicationDidFinishLaunching:))]
        fn application_did_finish_launching(
            &self,
            _notification: &NSNotification,
        ) {
            self.setup_ui();

            // Development builds only: exercise the keyboard policy through
            // real AppKit event dispatch, without any networking, then exit.
            #[cfg(debug_assertions)]
            if std::env::args().any(|argument| argument == UI_SELF_TEST_FLAG) {
                self.run_ui_self_test();

                return;
            }

            self.start_worker();
            self.start_state_timer();
        }
    }

    unsafe impl NSWindowDelegate for AppDelegate {
        #[unsafe(method(windowWillClose:))]
        fn window_will_close(
            &self,
            _notification: &NSNotification,
        ) {
            // Quit closes the window as part of terminating; that is not a
            // second user action.
            if self.ivars().quitting.get() {
                return;
            }

            logging::action("Window close");

            self.quit_application();
        }
    }

    impl AppDelegate {
        // ---------------------------------------------------------------------
        // Pull state messages from the worker thread
        // ---------------------------------------------------------------------

        #[unsafe(method(pollState:))]
        fn poll_state(
            &self,
            _timer: &NSTimer,
        ) {
            let states: Vec<AppState> = {
                let receiver =
                    self.ivars().receiver.borrow();

                match receiver.as_ref() {
                    Some(receiver) => {
                        receiver.try_iter().collect()
                    }

                    None => Vec::new(),
                }
            };

            for state in states {
                self.render_state(&state);
            }
        }


        // ---------------------------------------------------------------------
        // Retry after an error
        // ---------------------------------------------------------------------

        #[unsafe(method(retry:))]
        fn retry(
            &self,
            _sender: &AnyObject,
        ) {
            if self.ivars().worker_running.get() {
                return;
            }

            logging::action("Retry");

            self.start_worker();
        }


        #[unsafe(method(primaryAction:))]
        fn primary_action(
            &self,
            _sender: &AnyObject,
        ) {
            match self.ivars().primary_action.get() {
                PrimaryAction::Retry => {
                    logging::action("Retry");

                    self.start_worker();
                }

                PrimaryAction::Cancel => {
                    logging::action("Cancel");

                    self.cancel_active_session();
                }

                PrimaryAction::Stop => {
                    logging::action("Stop Stream");

                    self.cancel_active_session();
                }
            }
        }


        // ---------------------------------------------------------------------
        // Search again after playback has ended normally
        // ---------------------------------------------------------------------

        #[unsafe(method(search:))]
        fn search(
            &self,
            _sender: &AnyObject,
        ) {
            if self.ivars().worker_running.get() {
                return;
            }

            logging::action("Search");

            self.start_worker();
        }


        // ---------------------------------------------------------------------
        // Show this session's log directory in Finder
        // ---------------------------------------------------------------------

        #[unsafe(method(openLogs:))]
        fn open_logs(
            &self,
            _sender: &AnyObject,
        ) {
            self.open_logs_folder("button");
        }


        // Sent by MainWindow when the L shortcut is pressed.
        #[unsafe(method(openLogsFromKeyboard:))]
        fn open_logs_from_keyboard(
            &self,
            _sender: &AnyObject,
        ) {
            self.open_logs_folder("keyboard shortcut");
        }


        // Sent by MainWindow the first time it swallows a repeated activation
        // key during one key hold. `key` names the key.
        #[unsafe(method(keyRepeatSuppressed:))]
        fn key_repeat_suppressed(
            &self,
            key: &NSString,
        ) {
            logging::verbose(
                "UI",
                format_args!(
                    "Ignored repeated {key} activation for {} (one activation per key press)",
                    self.focused_button_name()
                ),
            );
        }


        // Sent by MainWindow just before a key press activates the focused
        // button. `key` names the key.
        #[unsafe(method(buttonActivatedByKey:))]
        fn button_activated_by_key(
            &self,
            key: &NSString,
        ) {
            logging::verbose(
                "UI",
                format_args!(
                    "Focused button activated via {key}: {}",
                    self.focused_button_name()
                ),
            );
        }


        // ---------------------------------------------------------------------
        // Quit PGC and terminate ffplay
        // ---------------------------------------------------------------------

        #[unsafe(method(quit:))]
        fn quit(
            &self,
            _sender: &AnyObject,
        ) {
            logging::action("Quit");

            self.quit_application();
        }
    }
);


