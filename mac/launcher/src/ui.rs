// -----------------------------------------------------------------------------
// Keyboard policy
//
// Decided once per key-down event, before AppKit dispatches it:
//
// - A key held down repeats. A repeated Space/Return must not activate a button
//   again: because focus follows the primary slot across state changes, a held
//   Space would otherwise press Search, then the Cancel that replaced it, then
//   Search again, many times a second. One physical press is one activation.
//
// - Plain L (either case, so Caps Lock works) opens the logs folder whenever
//   the window is active, whichever control has focus.
//
// - Nothing is intercepted while the user is typing into an editable control.
// -----------------------------------------------------------------------------

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum KeyFocus {
    // No control has keyboard focus.
    Window,

    Button,

    // An editable text control (or its field editor).
    TextInput,

    Other,
}


#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum KeyDecision {
    // Let AppKit handle the event normally.
    PassThrough,

    // Swallow: a repeat of a key that already acted once.
    SuppressRepeat,

    OpenLogsFolder,

    // Return / Enter on a focused button: click it. AppKit only does this by
    // itself for Space.
    ActivateFocusedButton,
}


struct KeyInput<'a> {
    // The key's characters, ignoring modifiers such as Shift.
    characters: &'a str,

    // Generated by the key being held down, not by a new press.
    is_repeat: bool,

    // Command, Control, or Option is held.
    has_command_modifier: bool,

    focus: KeyFocus,
}


// The name of a key that activates a focused button.
fn activation_key_name(characters: &str) -> Option<&'static str> {
    match characters {
        " " => Some("Space"),
        "\r" => Some("Return"),
        "\u{3}" => Some("Enter"),
        _ => None,
    }
}


fn key_decision(input: &KeyInput<'_>) -> KeyDecision {
    // Typing is never intercepted.
    if input.focus == KeyFocus::TextInput {
        return KeyDecision::PassThrough;
    }

    if input.has_command_modifier {
        return KeyDecision::PassThrough;
    }

    if input.characters.eq_ignore_ascii_case("l") {
        // Holding L opens the folder once, not once per repeat.
        return if input.is_repeat {
            KeyDecision::SuppressRepeat
        } else {
            KeyDecision::OpenLogsFolder
        };
    }

    // Only a button that actually has focus can be activated. With nothing
    // focused these keys do nothing: there is no default button.
    if input.focus != KeyFocus::Button {
        return KeyDecision::PassThrough;
    }

    match activation_key_name(input.characters) {
        None => KeyDecision::PassThrough,

        Some(_) if input.is_repeat => KeyDecision::SuppressRepeat,

        // AppKit activates a focused button on Space itself.
        Some("Space") => KeyDecision::PassThrough,

        Some(_) => KeyDecision::ActivateFocusedButton,
    }
}


// -----------------------------------------------------------------------------
// Main window
//
// An NSWindow that applies the keyboard policy above to its key-down events.
// Everything else is stock NSWindow behaviour.
// -----------------------------------------------------------------------------

struct MainWindowIvars {
    // Whether the current key hold has already been reported, so a held key
    // logs one Verbose line rather than one per repeat.
    repeat_reported: Cell<bool>,
}


define_class!(
    #[unsafe(super(NSWindow))]
    #[thread_kind = MainThreadOnly]
    #[name = "PGCMainWindow"]
    #[ivars = MainWindowIvars]
    struct MainWindow;

    unsafe impl NSObjectProtocol for MainWindow {}

    impl MainWindow {
        #[unsafe(method(sendEvent:))]
        fn send_event(
            &self,
            event: &NSEvent,
        ) {
            if event.r#type() == NSEventType::KeyDown
                && self.handle_key_down(event)
            {
                return;
            }

            let _: () = unsafe {
                msg_send![super(self), sendEvent: event]
            };
        }
    }
);


impl MainWindow {
    fn new(
        mtm: MainThreadMarker,
        content_rect: NSRect,
        style: NSWindowStyleMask,
    ) -> Retained<Self> {
        let this =
            Self::alloc(mtm).set_ivars(MainWindowIvars {
                repeat_reported: Cell::new(false),
            });

        unsafe {
            msg_send![
                super(this),
                initWithContentRect: content_rect,
                styleMask: style,
                backing: NSBackingStoreType::Buffered,
                defer: false,
            ]
        }
    }


    // Returns true when the event was consumed.
    fn handle_key_down(
        &self,
        event: &NSEvent,
    ) -> bool {
        let characters =
            event
                .charactersIgnoringModifiers()
                .map(|characters| characters.to_string())
                .unwrap_or_default();

        let modifiers =
            event.modifierFlags();

        let input = KeyInput {
            characters: &characters,

            is_repeat: event.isARepeat(),

            has_command_modifier:
                modifiers.contains(NSEventModifierFlags::Command)
                    || modifiers.contains(NSEventModifierFlags::Control)
                    || modifiers.contains(NSEventModifierFlags::Option),

            focus: self.key_focus(),
        };

        // A new press starts a new hold.
        if !input.is_repeat {
            self.ivars().repeat_reported.set(false);
        }

        let decision =
            key_decision(&input);

        // Verbose provenance for a key that is about to activate a button.
        let activates =
            !input.is_repeat
                && input.focus == KeyFocus::Button
                && matches!(
                    decision,
                    KeyDecision::PassThrough | KeyDecision::ActivateFocusedButton
                );

        if let (true, Some(key)) = (activates, activation_key_name(&characters)) {
            self.notify_delegate(
                sel!(buttonActivatedByKey:),
                &NSString::from_str(key),
            );
        }

        match decision {
            KeyDecision::PassThrough => false,

            KeyDecision::ActivateFocusedButton => {
                if let Some(first_responder) = self.firstResponder() {
                    if let Some(button) = first_responder.downcast_ref::<NSButton>() {
                        // Same as a click, including the brief pressed look.
                        unsafe {
                            button.performClick(None);
                        }
                    }
                }

                true
            }

            KeyDecision::SuppressRepeat => {
                // Report the first swallowed repeat of a hold, and only for
                // keys that would have activated a control.
                if let Some(key) = activation_key_name(&characters) {
                    if !self.ivars().repeat_reported.replace(true) {
                        self.notify_delegate(
                            sel!(keyRepeatSuppressed:),
                            &NSString::from_str(key),
                        );
                    }
                }

                true
            }

            KeyDecision::OpenLogsFolder => {
                self.notify_delegate(
                    sel!(openLogsFromKeyboard:),
                    self,
                );

                true
            }
        }
    }


    // What kind of control currently has keyboard focus.
    fn key_focus(&self) -> KeyFocus {
        let Some(first_responder) = self.firstResponder() else {
            return KeyFocus::Window;
        };

        let window: &NSResponder =
            self;

        if std::ptr::eq(&*first_responder, window) {
            return KeyFocus::Window;
        }

        if first_responder.downcast_ref::<NSButton>().is_some() {
            return KeyFocus::Button;
        }

        // A text field being edited makes its field editor (an NSText) the
        // first responder.
        if let Some(text) = first_responder.downcast_ref::<NSText>() {
            if text.isEditable() {
                return KeyFocus::TextInput;
            }
        }

        KeyFocus::Other
    }


    fn notify_delegate(
        &self,
        action: Sel,
        argument: &AnyObject,
    ) {
        let Some(delegate) = self.delegate() else {
            return;
        };

        let delegate: &AnyObject =
            delegate.as_ref();

        if delegate.class().responds_to(action) {
            // performSelector:withObject: returns an object; it is not used.
            let _: *mut AnyObject = unsafe {
                msg_send![delegate, performSelector: action, withObject: argument]
            };
        }
    }
}


// -----------------------------------------------------------------------------
// Hover feedback for the main buttons
//
// A standard push button that lightens while the pointer is over it. Shape,
// size, title, pressed look, and the keyboard focus ring are all AppKit's own.
// Hover is a faint rounded overlay on top of the bezel, in the same neutral
// fill as the utility shelf, shown and hidden by pointer enter/exit events
// only (no polling). Because the overlay is added to whatever AppKit draws,
// a pressed button under the pointer is visibly stronger than a hovered one.
// -----------------------------------------------------------------------------

define_class!(
    #[unsafe(super(NSButton))]
    #[thread_kind = MainThreadOnly]
    #[name = "PGCHoverButton"]
    struct HoverButton;

    unsafe impl NSObjectProtocol for HoverButton {}

    impl HoverButton {
        #[unsafe(method(mouseEntered:))]
        fn mouse_entered(
            &self,
            _event: &NSEvent,
        ) {
            self.set_hovered(true);
        }


        #[unsafe(method(mouseExited:))]
        fn mouse_exited(
            &self,
            _event: &NSEvent,
        ) {
            self.set_hovered(false);
        }


        // A button hidden while hovered never receives mouseExited, so clear
        // the tint here rather than showing it stale when it reappears.
        #[unsafe(method(viewDidHide))]
        fn view_did_hide(&self) {
            self.set_hovered(false);

            let _: () = unsafe {
                msg_send![super(self), viewDidHide]
            };
        }


        // A button shown under a stationary pointer (for example Cancel
        // replacing Search for Host after a click) gets no mouseEntered until
        // the pointer moves, so check where the pointer is.
        #[unsafe(method(viewDidUnhide))]
        fn view_did_unhide(&self) {
            let _: () = unsafe {
                msg_send![super(self), viewDidUnhide]
            };

            self.set_hovered(
                self.pointer_is_inside()
            );
        }
    }
);


impl HoverButton {
    // The same button `NSButton::buttonWithTitle_target_action` makes, as a
    // HoverButton, returned as the NSButton the rest of the UI works with.
    fn push_button(
        title: &NSString,
        target: &AnyObject,
        action: Sel,
    ) -> Retained<NSButton> {
        let button: Retained<HoverButton> = unsafe {
            msg_send![
                Self::class(),
                buttonWithTitle: title,
                target: target,
                action: action,
            ]
        };

        // Follows the button's visible area automatically, so it never needs
        // rebuilding when the button moves or resizes.
        let tracking = unsafe {
            NSTrackingArea::initWithRect_options_owner_userInfo(
                NSTrackingArea::alloc(),
                NSRect::new(
                    NSPoint::new(0.0, 0.0),
                    NSSize::new(0.0, 0.0),
                ),
                NSTrackingAreaOptions::MouseEnteredAndExited
                    | NSTrackingAreaOptions::ActiveInActiveApp
                    | NSTrackingAreaOptions::InVisibleRect,
                Some(&button),
                None,
            )
        };

        button.addTrackingArea(&tracking);


        // The hover overlay. Its frame is set each time it is shown, from the
        // button's size at that moment.
        let overlay =
            NSBox::initWithFrame(
                NSBox::alloc(button.mtm()),
                hover_overlay_frame(button.bounds().size),
            );

        overlay.setBoxType(NSBoxType::Custom);
        overlay.setTitlePosition(NSTitlePosition::NoTitle);
        overlay.setBorderWidth(0.0);
        overlay.setCornerRadius(HOVER_CORNER_RADIUS);
        overlay.setFillColor(&hover_fill_colour());

        overlay.setHidden(true);

        // The overlay does not handle the mouse, so clicks on it continue up
        // to the button as usual.
        button.addSubview(&overlay);

        Retained::into_super(button)
    }


    fn hover_overlay(&self) -> Option<Retained<NSBox>> {
        self.subviews()
            .iter()
            .find_map(|view| view.downcast::<NSBox>().ok())
    }


    fn set_hovered(
        &self,
        hovered: bool,
    ) {
        if let Some(overlay) = self.hover_overlay() {
            if hovered {
                overlay.setFrame(
                    hover_overlay_frame(self.bounds().size)
                );
            }

            overlay.setHidden(!hovered);
        }
    }


    fn pointer_is_inside(&self) -> bool {
        let Some(window) = self.window() else {
            return false;
        };

        let pointer =
            self.convertPoint_fromView(
                window.mouseLocationOutsideOfEventStream(),
                None,
            );

        let bounds =
            self.bounds();

        pointer.x >= bounds.origin.x
            && pointer.y >= bounds.origin.y
            && pointer.x < bounds.origin.x + bounds.size.width
            && pointer.y < bounds.origin.y + bounds.size.height
    }
}


// Matches the corner rounding of a standard push button closely enough that
// the overlay reads as the button itself brightening.
const HOVER_CORNER_RADIUS: f64 = 6.0;


// The same faint, appearance-aware fill as the utility shelf.
fn hover_fill_colour() -> Retained<NSColor> {
    NSColor::quaternaryLabelColor()
}


// Height of a regular-size push button's visible bezel. The button's frame is
// taller than what it draws; the bezel is centred vertically and spans the
// full width.
const PUSH_BUTTON_BEZEL_HEIGHT: f64 = 24.0;


// The part of a push button of `size` that its bezel occupies.
fn hover_overlay_frame(size: NSSize) -> NSRect {
    let height =
        PUSH_BUTTON_BEZEL_HEIGHT.min(size.height);

    NSRect::new(
        NSPoint::new(
            0.0,
            (size.height - height) / 2.0,
        ),
        NSSize::new(size.width, height),
    )
}


