pub fn run_app() {
    let mtm =
        MainThreadMarker::new()
            .expect(
                "Portable Game Caster must start on the macOS main thread"
            );


    let app =
        NSApplication::sharedApplication(
            mtm
        );


    let delegate =
        AppDelegate::new(
            mtm
        );


    app.setDelegate(
        Some(
            ProtocolObject::from_ref(
                &*delegate
            )
        )
    );


    app.run();
}


// -----------------------------------------------------------------------------
// Utility shelf layout
//
// Positions are computed, so adding an icon is a matter of raising the count.
// -----------------------------------------------------------------------------

const WINDOW_CONTENT_WIDTH: f64 = 460.0;
const WINDOW_CONTENT_HEIGHT: f64 = 230.0;

// Icons on the shelf today: Open Logs Folder.
const UTILITY_BUTTON_COUNT: usize = 1;

const UTILITY_BUTTON_SIZE: f64 = 24.0;
const UTILITY_BUTTON_GAP: f64 = 4.0;
const UTILITY_SHELF_PADDING: f64 = 5.0;
const UTILITY_SHELF_TOP_MARGIN: f64 = 12.0;
const UTILITY_SHELF_RIGHT_MARGIN: f64 = 14.0;


// The shelf in window content coordinates: hugging the top-right corner and
// growing leftwards as buttons are added.
fn utility_shelf_frame(button_count: usize) -> NSRect {
    let count = button_count.max(1) as f64;

    let width =
        2.0 * UTILITY_SHELF_PADDING
            + count * UTILITY_BUTTON_SIZE
            + (count - 1.0) * UTILITY_BUTTON_GAP;

    let height =
        2.0 * UTILITY_SHELF_PADDING + UTILITY_BUTTON_SIZE;

    NSRect::new(
        NSPoint::new(
            WINDOW_CONTENT_WIDTH - UTILITY_SHELF_RIGHT_MARGIN - width,
            WINDOW_CONTENT_HEIGHT - UTILITY_SHELF_TOP_MARGIN - height,
        ),
        NSSize::new(width, height),
    )
}


// A button's frame inside the shelf, left to right.
fn utility_button_frame(index: usize) -> NSRect {
    NSRect::new(
        NSPoint::new(
            UTILITY_SHELF_PADDING
                + index as f64 * (UTILITY_BUTTON_SIZE + UTILITY_BUTTON_GAP),
            UTILITY_SHELF_PADDING,
        ),
        NSSize::new(UTILITY_BUTTON_SIZE, UTILITY_BUTTON_SIZE),
    )
}


// Shared look for shelf buttons: icon only, with AppKit's own hover treatment
// (the bezel is drawn only while the pointer is inside). Keyboard focus keeps
// its separate system focus ring.
fn style_utility_button(button: &NSButton) {
    button.setBezelStyle(NSBezelStyle::AccessoryBarAction);
    button.setBordered(true);
    button.setShowsBorderOnlyWhileMouseInside(true);
    button.setImagePosition(NSCellImagePosition::ImageOnly);
}


// Checks, at runtime, that a utility button really is a child of the shelf and
// sits inside it. Verbose reports the result; a wrong parent is a warning,
// because the button would then be drawn somewhere else in the window.
fn report_shelf_placement(
    name: &str,
    button: &NSButton,
    shelf_content: &NSView,
    shelf: &NSBox,
) {
    let parent =
        unsafe { button.superview() };

    let parented =
        parent.is_some_and(|parent| std::ptr::eq(&*parent, shelf_content));

    let frame =
        button.frame();

    let inside =
        frame_fits_within(frame, shelf.frame().size);

    if parented && inside {
        logging::verbose(
            "UI",
            format_args!(
                "Utility shelf: {name} is a child of the shelf at ({}, {}) in a {}x{} shelf whose window origin is ({}, {})",
                frame.origin.x,
                frame.origin.y,
                shelf.frame().size.width,
                shelf.frame().size.height,
                shelf.frame().origin.x,
                shelf.frame().origin.y
            ),
        );
    } else {
        logging::warn(
            "APP",
            format_args!(
                "Utility shelf layout problem: {name} parented to shelf: {parented}; inside shelf bounds: {inside}"
            ),
        );
    }
}


// Whether `frame` (in the container's coordinates) lies inside a container of
// `size`.
fn frame_fits_within(frame: NSRect, size: NSSize) -> bool {
    frame.origin.x >= 0.0
        && frame.origin.y >= 0.0
        && frame.origin.x + frame.size.width <= size.width
        && frame.origin.y + frame.size.height <= size.height
}


// -----------------------------------------------------------------------------
// Keyboard focus across state changes
// -----------------------------------------------------------------------------

// The two controls that share the primary action slot.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum SlotControl {
    // Retry / Cancel / Stop Stream.
    Primary,

    // Search for Host.
    Search,
}


#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum FocusDecision {
    // The focused control is still there.
    Keep,

    // The focused control was replaced in its slot: follow it.
    Transfer(SlotControl),

    // The focused control is gone and nothing took its place.
    Clear,
}


// `focused` had keyboard focus before the transition; the visibility flags
// describe the slot after it.
fn focus_after_transition(
    focused: SlotControl,
    primary_visible: bool,
    search_visible: bool,
) -> FocusDecision {
    let visible = |control| match control {
        SlotControl::Primary => primary_visible,
        SlotControl::Search => search_visible,
    };

    let other = match focused {
        SlotControl::Primary => SlotControl::Search,
        SlotControl::Search => SlotControl::Primary,
    };

    if visible(focused) {
        FocusDecision::Keep
    } else if visible(other) {
        FocusDecision::Transfer(other)
    } else {
        FocusDecision::Clear
    }
}


// -----------------------------------------------------------------------------
// Shutdown
